import postcss from 'postcss';
import type { AcceptedPlugin, Plugin, Root } from 'postcss';
import combineDuplicatedSelectors from 'postcss-combine-duplicated-selectors';
import discardDuplicates from 'postcss-discard-duplicates';
import mqpacker from 'mqpacker';
import cssnano from 'cssnano';
import type { Mapping } from '../types.js';

// Plugins recopient `dsfr/tool/build/styles.js` (fonction `process`) :
//   mqpacker (sort:false) → combine-duplicated-selectors → discard-duplicates
// + un plugin inline pour le banner (5 lignes, évite la dep `postcss-banner`).
//
// `stylelint --fix` de la pipeline DSFR est volontairement retiré : ce step
// vise à normaliser du SCSS écrit à la main, pas du généré, et tourne 5-10x
// plus lentement que le reste. `cssnano` n'intervient qu'en mode --minify.

function bannerPlugin(text: string): Plugin {
  return {
    postcssPlugin: 'ademe-banner',
    Once(root: Root) {
      const has = root.first && root.first.type === 'comment' && root.first.text.includes('ADEME');
      if (!has) root.prepend(postcss.comment({ text: ` ${text} ` }));
    }
  };
}

const NORMAL_PLUGINS = (banner: string | null | undefined): AcceptedPlugin[] => [
  mqpacker({ sort: false }),
  combineDuplicatedSelectors,
  discardDuplicates,
  ...(banner ? [bannerPlugin(banner)] : [])
];

// La passe minify tourne sur le CSS déjà dédupé, donc seul `cssnano` est utile
// (+ re-prepend du banner puisque cssnano vire les commentaires).
const MINIFY_PLUGINS = (banner: string | null | undefined): AcceptedPlugin[] => [
  cssnano({ preset: ['default', { discardComments: { removeAll: true } }] }),
  ...(banner ? [bannerPlugin(banner)] : [])
];

interface PostcssProcessOpts {
  banner?: string | null;
  minify?: boolean;
  from?: string;
  to?: string;
}

interface PostcssProcessResult {
  css: string;
  minCss: string | null;
}

/**
 * Lance la pipeline PostCSS sur un string CSS (aucun I/O disque). Renvoie le
 * CSS dédupé et, si `minify` est vrai, sa variante minifiée.
 */
export async function postcssProcess(css: string, opts: PostcssProcessOpts = {}): Promise<PostcssProcessResult> {
  const banner = opts.banner;
  const processOpts: { from?: string; to?: string } = {};
  if (opts.from !== undefined) processOpts.from = opts.from;
  if (opts.to !== undefined) processOpts.to = opts.to;

  const normal = await postcss(NORMAL_PLUGINS(banner))
    .process(css, processOpts);

  let minCss: string | null = null;
  if (opts.minify) {
    const minified = await postcss(MINIFY_PLUGINS(banner))
      .process(css, processOpts);
    minCss = minified.css;
  }

  return { css: normal.css, minCss };
}

/**
 * Banner par défaut — court, marqué ADEME. La version DSFR vient de
 * `mapping.yml` pour rester en sync avec le submodule épinglé.
 */
export function defaultBanner(mapping: Mapping | null): string {
  const dsfr = mapping?.dsfr ?? 'unknown';
  return `ADEME Design System — based on DSFR ${dsfr} (MIT) — generated by dsfr-override`;
}
