import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { load as parseYaml } from 'js-yaml';
import postcss from 'postcss';
import * as sass from 'sass';
import type { CompileResult, Mapping } from '../types.js';
import { compile } from './compile.js';
import { postcssProcess } from './postcss-process.js';
import { prepare } from './prepare.js';
import { restore } from './restore.js';

interface BuildOverlayArgs {
  projectRoot: string;
  minify: boolean;
}

export interface BuildOverlayResult {
  outFile: string;
  minOutFile: string | null;
  rootBlocks: number;
  fontFaceBlocks: number;
  bytes: number;
  workspaceClean: boolean;
  workspaceDirty: string;
}

/**
 * Mode "overlay" : produit un seul `dist/ademe-overlay.css` destiné à être
 * chargé PAR-DESSUS le DSFR upstream (ex : celui shippé par react-dsfr).
 *
 * Stratégie : on lance le pipeline complet de build (palette LCh injectée dans
 * `_options.scss`, compile sass), puis on extrait du CSS produit uniquement
 * les blocs `:root` (palette + decisions). On y concatène la compilation
 * standalone de `overrides/_index.scss` qui apporte nos `@font-face` Public
 * Sans aliasés Marianne ainsi que les overrides class-based (radius, icons,
 * fixes alert/card).
 *
 * Contraintes mode overlay :
 *  - `post-process.rename` est forcé désactivé via `overrideMappingForOverlay`
 *    (court-circuit du mapping disque) : react-dsfr hardcode des refs
 *    `--blue-france-*` / `--red-marianne-*` dans son JS (mui.tsx, etc.) ; tout
 *    rename casse silencieusement MUI/charts. Les valeurs sont ADEME, les
 *    noms de tokens restent upstream.
 *  - `components.remove` est vidé : l'overlay ne porte pas la responsabilité
 *    de retirer des composants DSFR. Filtrer le SCSS upstream en amont
 *    n'aurait pas d'impact sur l'overlay (on n'extrait que les `:root`),
 *    mais on évite tout de même un transform inutile sur le workspace.
 */
export async function buildOverlay(args: BuildOverlayArgs): Promise<BuildOverlayResult> {
  const mappingPath = join(args.projectRoot, 'mapping.yml');
  const baseMapping: Mapping | null = existsSync(mappingPath)
    ? (parseYaml(readFileSync(mappingPath, 'utf8')) as Mapping | null)
    : null;
  const overlayMapping = baseMapping ? overrideMappingForOverlay(baseMapping) : null;

  const input = prepare({ projectRoot: args.projectRoot, mapping: overlayMapping });

  let results: CompileResult[] = [];
  let buildErr: unknown;
  try {
    results = await compile(input);
  } catch (e) {
    buildErr = e;
  }
  const status = await restore({ projectRoot: args.projectRoot });
  if (buildErr) throw buildErr;

  const dsfrResult = results.find(r => r.name === 'dsfr');
  if (!dsfrResult) throw new Error('overlay: no dsfr target produced by compile()');

  const extracted = extractRootAndFontFaces(dsfrResult.css);
  const overridesCss = compileOverridesStandalone(args.projectRoot);

  const banner = `ADEME Design System overlay — based on DSFR ${overlayMapping?.dsfr ?? 'unknown'} (MIT) — generated by dsfr-override`;
  const fullCss = [extracted.css, overridesCss].join('\n\n');
  const processed = await postcssProcess(fullCss, {
    banner,
    minify: args.minify,
    from: 'overlay',
    to: 'overlay'
  });

  const outFile = join(input.distDir, 'ademe-overlay.css');
  writeFileSync(outFile, processed.css);
  let minOutFile: string | null = null;
  if (processed.minCss != null) {
    minOutFile = join(input.distDir, 'ademe-overlay.min.css');
    writeFileSync(minOutFile, processed.minCss);
  }

  return {
    outFile,
    minOutFile,
    rootBlocks: extracted.rootBlocks,
    fontFaceBlocks: extracted.fontFaceBlocks,
    bytes: Buffer.byteLength(processed.css, 'utf8'),
    workspaceClean: status.clean,
    workspaceDirty: status.dirty
  };
}

/**
 * Retire les sections du mapping incompatibles avec un usage overlay. Ce
 * mapping override est passé à `prepare()` via `PrepareOpts.mapping` pour
 * court-circuiter la lecture du `mapping.yml` disque.
 */
function overrideMappingForOverlay(mapping: Mapping): Mapping {
  const next: Mapping = { ...mapping };
  next['post-process'] = {
    ...mapping['post-process'],
    rename: { ...(mapping['post-process']?.rename ?? {}), enabled: false }
  };
  if (mapping.components?.remove?.length) {
    next.components = { ...mapping.components, remove: [] };
  }
  return next;
}

interface ExtractResult {
  css: string;
  rootBlocks: number;
  fontFaceBlocks: number;
}

/**
 * Garde uniquement, au top-level :
 *  - les rules dont le sélecteur est un `:root` "pur" (eventuellement qualifié
 *    par un attribut, une classe ou une pseudo-classe sur :root lui-même —
 *    `:root[data-fr-theme=dark]`, `:root.fr-no-js`) mais sans chaining vers
 *    un descendant DOM (`:root body`, `:root .fr-logo`). Détection : aucun
 *    espace, `>`, `+`, `~` ou virgule après le préfixe `:root`. Cette
 *    whitelist explicite vaut mieux qu'une blacklist par token : un futur
 *    sélecteur `:root:has(.fr-foo)` ou `:root .fr-bar` ne traverse pas par
 *    accident.
 *  - les `@font-face` SAUF ceux qui pointent vers la famille `Marianne` :
 *    DSFR upstream émet ces stubs vers des fichiers `Marianne-*.woff2` que
 *    `dsfr-override` ne ship pas (Marianne est exclue pour raisons légales).
 *    Notre `compileOverridesStandalone` re-définit la famille `Marianne` avec
 *    Public Sans plus bas dans le concat, ce qui suffit.
 */
function extractRootAndFontFaces(css: string): ExtractResult {
  const root = postcss.parse(css);
  const out: string[] = [];
  let rootBlocks = 0;
  let fontFaceBlocks = 0;

  root.each(node => {
    if (node.type === 'rule') {
      const sel = node.selector.trim();
      if (!sel.startsWith(':root')) return;
      const afterRoot = sel.slice(5);
      if (/[\s>+~,]/.test(afterRoot)) return;
      out.push(node.toString());
      rootBlocks++;
    } else if (node.type === 'atrule' && node.name === 'font-face') {
      const block = node.toString();
      if (/font-family\s*:\s*['"]?Marianne['"]?\s*[;}]/i.test(block)) return;
      out.push(block);
      fontFaceBlocks++;
    }
  });

  return { css: out.join('\n\n'), rootBlocks, fontFaceBlocks };
}

/**
 * Compile `overrides/_index.scss` sans contexte DSFR. Les overrides sont du
 * CSS pur (font-face, classes `fr-*`) qui réfèrent des CSS variables DSFR
 * résolues à runtime — pas de dépendance Sass au submodule.
 */
function compileOverridesStandalone(projectRoot: string): string {
  const overridesIndex = resolve(projectRoot, 'overrides/_index.scss');
  const result = sass.compile(overridesIndex, {
    style: 'expanded',
    silenceDeprecations: ['import']
  });
  return result.css;
}
