import postcss from 'postcss';
import combineDuplicatedSelectors from 'postcss-combine-duplicated-selectors';
import discardDuplicates from 'postcss-discard-duplicates';
import mqpacker from 'mqpacker';
import cssnano from 'cssnano';

/**
 * Plugins reproduce dsfr/tool/build/styles.js (function `process`):
 *   mqpacker (sort:false) → combine-duplicated-selectors → discard-duplicates
 * + an inline banner plugin (5 lines, avoids the `postcss-banner` dep).
 *
 * stylelint --fix from the DSFR pipeline is intentionally dropped: that step
 * is meant to normalise hand-written SCSS, not generated output, and runs 5-10x
 * slower than the rest of the pipeline. cssnano is only invoked when minifying.
 */

function bannerPlugin(text) {
  return {
    postcssPlugin: 'ademe-banner',
    Once(root) {
      const has = root.first && root.first.type === 'comment' && root.first.text.includes('ADEME');
      if (!has) root.prepend(postcss.comment({ text: ` ${text} ` }));
    }
  };
}
bannerPlugin.postcss = true;

const NORMAL_PLUGINS = (banner) => [
  mqpacker({ sort: false }),
  combineDuplicatedSelectors,
  discardDuplicates,
  ...(banner ? [bannerPlugin(banner)] : [])
];

const MINIFY_PLUGINS = (banner) => [
  mqpacker({ sort: false }),
  combineDuplicatedSelectors,
  discardDuplicates,
  cssnano({ preset: ['default', { discardComments: { removeAll: true } }] }),
  ...(banner ? [bannerPlugin(banner)] : [])
];

/**
 * Run PostCSS over a CSS string (no disk I/O).
 *
 * @param {string} css
 * @param {object} [opts]
 * @param {string} [opts.banner]    Banner text. Falsy → no banner is prepended.
 * @param {boolean} [opts.minify=false]  Also produce a minified flavor.
 * @param {string} [opts.from]      Passed to postcss for source maps.
 * @param {string} [opts.to]        Idem.
 * @returns {Promise<{ css: string, minCss: string | null }>}
 */
export async function postcssProcess(css, opts = {}) {
  const banner = opts.banner;
  const normal = await postcss(NORMAL_PLUGINS(banner))
    .process(css, { from: opts.from, to: opts.to });

  let minCss = null;
  if (opts.minify) {
    const minified = await postcss(MINIFY_PLUGINS(banner))
      .process(css, { from: opts.from, to: opts.to });
    minCss = minified.css;
  }

  return { css: normal.css, minCss };
}

/**
 * Default banner text — short, ADEME-flavoured. The DSFR version comes from
 * mapping.yml so it stays in sync with the pinned submodule.
 */
export function defaultBanner(mapping) {
  const dsfr = mapping?.dsfr ?? 'unknown';
  return `ADEME Design System — based on DSFR ${dsfr} (MIT) — generated by dsfr-override`;
}
